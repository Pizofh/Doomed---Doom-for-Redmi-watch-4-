local M=assert(load(OWN_SOURCE,'own-observation','t',{type=type,string=string,ipairs=ipairs,tonumber=tonumber}))()
local f=assert(io.open('/tmp/rw4proc-own-tests-r248/observed.bin','rb'));local actual=f:read(67);assert(f:close())
local passed=0
local function check(text,expected)
    local r=M.inspect(text);assert(r.ownObserved==expected)
    assert(r.metadataComplete==false and r.inventoryComplete==false and r.readyToUnload==nil)
    if expected then assert(r.kind=='OwnClippedRecord' and r.dataSizeKnown==false and r.textBytes==972 and r.uninitializerOffset==321)end
    passed=passed+1
end
check(actual,true)
local function example(base,data)
    return string.format('rw4step234,0x%08x,0x%08x,0,0,0x%08x,972,0x%08x,',base+1,base+321,base,data)..string.rep('\0',3)
end
local fixture=example(0x20100000,0x20110000)
check(fixture,true)
check(example(0x30100000,0x30110000),true)
check(fixture:gsub('20100001','20100003'),false)
check(fixture:gsub('20100141','20100143'),false)
check(fixture:gsub(',972,',',973,'),false)
check(fixture:gsub(',0,0,',',0,1,'),false)
check(fixture:gsub(',0,0,',',1,0,'),false)
check(fixture:gsub('rw4step234','rw4step235'),false)
check(example(0x20100000,0x20110001),false)
check(example(0x20100004,0x20110000),false)
check(example(0x20100000,0),false)
check(fixture:sub(1,-2),false)
check(fixture..'\0',false)
check(fixture:sub(1,-2)..'x',false)
check(fixture:sub(1,63)..'36\n',false) -- not the clipped format, no generic acceptance
check('',false)
check('NAME INIT UNINIT ARG NEXPORTS TEXT SIZE DATA SIZE\n',false)
check(fixture..fixture,false)
check(fixture:gsub(',0,0,',',-1,0,'),false)
check(example(0xfffffe00,0x20110000),false)
