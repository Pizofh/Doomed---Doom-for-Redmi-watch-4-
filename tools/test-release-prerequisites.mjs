import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {checkPrerequisites} from './check-release-prerequisites.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
const fixture = path.join(root, 'artifacts/research/prerequisites-r356-fixture');
assert(!fs.existsSync(fixture), 'Fixture exists');
fs.mkdirSync(fixture, {recursive: true});
const empty = checkPrerequisites(fixture);
assert.equal(empty.upstream.status, 'invalid-or-missing-lock');
assert.equal(empty.issues.length, 10);
assert.equal(empty.cleanCheckoutBuildSupported, false);
fs.mkdirSync(path.join(fixture, 'doom'));
fs.copyFileSync(path.join(root, 'doom/doomgeneric-source.lock.json'), path.join(fixture, 'doom/doomgeneric-source.lock.json'));
const missing = checkPrerequisites(fixture);
assert.equal(missing.upstream.status, 'incomplete');
assert.equal(missing.upstream.verified, 0);
assert.equal(missing.issues.length, 191);
const compiler = path.join(fixture, 'tools/local/arm-14.3-review/bin');
fs.mkdirSync(compiler, {recursive: true});
fs.writeFileSync(path.join(compiler, 'arm-none-eabi-gcc.exe'), 'not executable: fixture');
assert.equal(checkPrerequisites(fixture).issues.find(i => i.name === 'Arm GCC').status, 'changed');
const local = checkPrerequisites(root);
assert.equal(local.upstream.status, 'verified');
assert.equal(local.upstream.verified, 181);
assert.equal(local.issues.length, 0);
assert.equal(local.privateConnectionDataRead, false);
console.log(JSON.stringify({passed: true, scenarios: ['empty checkout', 'missing upstream', 'changed compiler', 'current pinned workspace'], deviceOperationPerformed: false}));
